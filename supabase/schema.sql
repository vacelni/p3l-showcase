-- =====================================================================
-- Base tables. The production tables were created in the Supabase
-- dashboard; this file reconstructs them from the application code
-- (lib/types.ts, app/admin/actions.ts) so a fresh project can be set up
-- from the repository alone.
--
-- Setup order on a new Supabase project (SQL Editor):
--   1. schema.sql          (this file)
--   2. schedule-link.sql   registrations.schedule_id + payment status check
--   3. seo-title.sql       insights.seo_title
--   4. rls.sql             row-level security
--   5. rate-limit.sql      shared rate limiter
--   6. seed.sql            optional demo data
-- =====================================================================

create extension if not exists pgcrypto;

create table if not exists public.schedules (
  id               integer generated by default as identity primary key,
  title            text        not null check (char_length(title) <= 200),
  category         text        not null default 'Non-BNSP',
  date_start       date        not null,
  date_end         date        not null,
  price            text,
  location         text        not null,
  min_participants integer     check (min_participants is null or min_participants > 0),
  is_active        boolean     not null default true,
  description      text,
  syllabus         text        check (syllabus is null or char_length(syllabus) <= 5000),
  created_at       timestamptz not null default now(),
  constraint schedules_dates_ordered check (date_end >= date_start)
);

create table if not exists public.insights (
  id               integer generated by default as identity primary key,
  title            text        not null check (char_length(title) <= 200),
  type             text        not null default 'Artikel',
  category         text        not null default 'Umum',
  date             date        not null default current_date,
  excerpt          text        not null,
  external_pdf_url text,
  event_location   text,
  event_date       text,
  is_active        boolean     default true,
  created_at       timestamptz not null default now()
);

-- Personal data of registrants: no public policy (see rls.sql), server-only access.
create table if not exists public.registrations (
  id                uuid        primary key default gen_random_uuid(),
  nama_lengkap      text        not null,
  jabatan           text        not null,
  instansi          text        not null,
  alamat_instansi   text        not null,
  whatsapp          text        not null,
  email_korporat    text        not null,
  program_pilihan   text        not null,
  status_pembayaran text,
  created_at        timestamptz not null default now()
);

-- Duplicate-invoice check in app/api/register/route.ts filters on these columns.
create index if not exists registrations_email_created_idx
  on public.registrations (email_korporat, created_at desc);
create index if not exists schedules_active_start_idx
  on public.schedules (is_active, date_start);
